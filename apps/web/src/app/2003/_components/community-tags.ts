export function parseCommunityTags(value: string): string[] {
  const seen = new Set<string>();
  return value
    .split(/[,\r\n]+/)
    .map((tag) => tag.trim())
    .filter((tag) => {
      const key = tag.toLocaleLowerCase("mn");
      if (!key || seen.has(key)) return false;
      seen.add(key);
      return true;
    });
}
